// selector handles pkg.Name and recv.Method.
func (tr *translator) selector(x *ast.SelectorExpr) string {
	pkg := identName(x.X)
	if path, ok := tr.imports[pkg]; ok && pkg != "" {
		if path == "" {
			return pkg + "." + x.Sel.Name // fmt/testing handled in call()
		}
		// types living in other crates despite the qualifier used.
		if relocate, ok := relocatedTypes[pkg+"."+x.Sel.Name]; ok {
			return relocate
		}
		// package-level member: type names stay CamelCase; Go enum consts
		// `TypeNameVariant` map to `Type::VARIANT`; vars/fns -> snake.
		name := x.Sel.Name
		if pkg == "ls" && strings.HasPrefix(name, "SortText") &&
			len(name) > len("SortText") && unicode.IsUpper(rune(name[len("SortText")])) {
			return "tsc_ls::" + screaming(name[len("SortText"):])
		}
		if isTypeName(name) {
			return path + "::" + name
		}
		if snakeNames[name] {
			return path + "::" + snake(name)
		}
		if t, v, ok := enumConst(name); ok {
			rt := rustEnumType[t]
			if rt == "" {
				rt = t
			}
			if path == "tsc_lsproto" {
				if av, ok := pascalVariantAlias[t+"."+v]; ok {
					v = av
				}
				return path + "::" + rt + "::" + v // PascalCase consts
			}
			return path + "::" + rt + "::" + screaming(v)
		}
		return path + "::" + screaming(name)
	}
	recv := tr.expr(x.X)
	// `f.MarkerByName("n").field` — Option-returning accessor needs unwrap.
	if call, ok := x.X.(*ast.CallExpr); ok {
		if fs, ok2 := call.Fun.(*ast.SelectorExpr); ok2 &&
			optionReturnCalls[snake(fs.Sel.Name)] {
			recv += ".unwrap()"
		}
	}
	// LSP client-capability fields are Option<T>; unwrap intermediate hops.
	last := recv[strings.LastIndex(recv, ".")+1:]
	if capOptionFields[last] {
		recv += ".as_mut().unwrap()"
	}
	return recv + "." + snake(x.Sel.Name)
}

