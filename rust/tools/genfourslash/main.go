func enumConst(name string) (string, string, bool) {
	for _, t := range enumTypes {
		if strings.HasPrefix(name, t) && len(name) > len(t) {
			v := name[len(t):]
			if v != "" && unicode.IsUpper(rune(v[0])) {
				return t, v, true
			}
		}
	}
	return "", "", false
}

func isTypeName(name string) bool {
	// heuristic: Go test files name types after their struct usage; value
	// constants we know are the enum/preference names. Err toward const.
	typish := map[string]bool{
		"FourslashOptions": true, "VerifyCodeFixAllOptions": true,
		"VerifyCompletionsRequest": true, "Capabilities": true,
		"Marker": true, "RangeMarker": true,
		"ApplyCodeActionFromCompletionOptions": true,
	}
	return typish[name] || strings.HasSuffix(name, "Options") ||
		strings.HasSuffix(name, "Params") || strings.HasSuffix(name, "List") ||
		strings.HasSuffix(name, "Defaults") || strings.HasSuffix(name, "Item") ||
		strings.HasSuffix(name, "Items") || strings.HasSuffix(name, "Edits") ||
		strings.HasSuffix(name, "Capabilities") || strings.HasSuffix(name, "Preferences")
}

// call handles function/method calls including the `f.X(t, ...)` convention.
func (tr *translator) call(c *ast.CallExpr) string {
	// type conversion like `foo(...)` where fun is a type — handled by
	// generic path; specialize known ones.
	if sel, ok := c.Fun.(*ast.SelectorExpr); ok {
		pkg := identName(sel.X)
		switch {
		case pkg == "f" || pkg == "this":
			// f.Method(t, args...) -> f.method(args...)
			args := tr.args(c.Args, 1)
			return "f." + snake(sel.Sel.Name) + "(" + args + ")"

		case pkg == "fmt" && sel.Sel.Name == "Sprintf":
			return tr.sprintf(c)

		case pkg == "t" && sel.Sel.Name == "Skip":
			return fmt.Sprintf("return /* skip: %s */", tr.args(c.Args, 0))

		case pkg == "t" && (sel.Sel.Name == "Fatal" || sel.Sel.Name == "Fatalf" ||
			sel.Sel.Name == "Error" || sel.Sel.Name == "Errorf"):
			if strings.HasSuffix(sel.Sel.Name, "f") {
				return tr.sprintfTo(c, "panic!")
			}
			return "panic!(" + tr.args(c.Args, 0) + ")"

		case pkg == "t" && sel.Sel.Name == "Name":
			return "t_name()"

		case pkg == "t" && sel.Sel.Name == "Parallel":
			return "/* t.Parallel */ ()"

		case pkg == "t" && sel.Sel.Name == "Helper":
			return "/* t.Helper */ ()"

		case pkg == "testing" || pkg == "testutil" || pkg == "util":
			path := tr.imports[pkg]
			if path == "" {
				path = pkg
			}
			return path + "::" + snake(sel.Sel.Name) + "(" + tr.args(c.Args, 0) + ")"

		case pkg == "fourslash" && sel.Sel.Name == "NewFourslash":
			return "tsc_fourslash::new_fourslash(t_name(), \"\", " +
				tr.expr(c.Args[1]) + ", " + tr.expr(c.Args[2]) + ")"
		case pkg == "fourslash" && sel.Sel.Name == "NewFourslashWithOptions":
			return "tsc_fourslash::new_fourslash_with_options(t_name(), \"\", " +
				tr.expr(c.Args[1]) + ", " + tr.expr(c.Args[2]) + ")"
		case tr.imports[pkg] != "":
			// package function call
			return tr.imports[pkg] + "::" + snake(sel.Sel.Name) + "(" + tr.args(c.Args, 0) + ")"
		}
		// method call on other receivers: x.Method(...) -> x.method(...)
		return tr.expr(sel.X) + "." + snake(sel.Sel.Name) + "(" + tr.args(c.Args, 0) + ")"
	}
	if id, ok := c.Fun.(*ast.Ident); ok {
		switch id.Name {
		case "panic":
			return "panic!(" + tr.args(c.Args, 0) + ")"
		case "len":
			return tr.expr(c.Args[0]) + ".len()"
		case "append":
			return tr.expr(c.Args[0]) + ".push(" + tr.args(c.Args[1:], 0) + ")"
		case "string":
			return tr.expr(c.Args[0]) + ".to_string()"
		case "new":
			return "Some((" + tr.expr(c.Args[0]) + ").into())"
		case "int", "int32", "int64", "uint", "uint32", "uint64", "byte", "rune", "float64":
			return "(" + tr.args(c.Args, 0) + ") as " + goIntRust(id.Name)
		case "cap":
			return tr.expr(c.Args[0]) + ".capacity()"
		case "copy":
			return tr.args(c.Args, 0) + "/* copy */"
		case "delete":
			return tr.expr(c.Args[0]) + ".remove(" + tr.args(c.Args[1:], 0) + ")"
		case "make":
			return tr.make(c)
		}
		return snake(id.Name) + "(" + tr.args(c.Args, 0) + ")"
	}
	note(tr.fset, c, "unhandled call fun %T", c.Fun)
	return tr.expr(c.Fun) + "(" + tr.args(c.Args, 0) + ")"
}

func goIntRust(name string) string {
	switch name {
	case "rune", "int32":
		return "i32"
	case "int":
		return "i32"
	case "byte":
		return "u8"
	}
	return name
}

// make handles make([]T, n)/make(map..)/make(chan).
func (tr *translator) make(c *ast.CallExpr) string {
	if len(c.Args) == 0 {
		return "Default::default()"
	}
	switch c.Args[0].(type) {
	case *ast.ArrayType:
		if len(c.Args) > 1 {
			return "vec![Default::default(); " + tr.expr(c.Args[1]) + "]"
		}
		return "Vec::new()"
	case *ast.MapType:
		return "FxHashMap::default()"
	case *ast.ChanType:
		return "mpsc::channel().0"
	}
	note(tr.fset, c, "make type %T", c.Args[0])
	return "Default::default()"
}

// args renders a comma-separated arg list, skipping the first `skip` args.
// A bare `t` argument is the *testing.T -> `&mut t`.
func (tr *translator) args(list []ast.Expr, skip int) string {
	if skip > len(list) {
		skip = len(list)
	}
	var out []string
	for _, a := range list[skip:] {
		if identName(a) == "t" {
			out = append(out, "&mut *t")
			continue
		}
		out = append(out, tr.expr(a))
	}
	return strings.Join(out, ", ")
}

// mutNames prefixes `mut ` on every binding except `_done`/`_`.
func mutNames(names []string) []string {
	for i, n := range names {
		if n != "_" && n != "_done" {
			names[i] = "mut " + n
		}
	}
	return names
}

// sprintf converts fmt.Sprintf("...", args) -> format!("...", args),
// translating Go verbs to Rust formatting specifiers.
func (tr *translator) sprintf(c *ast.CallExpr) string {
	args := tr.args(c.Args, 0)
	if lit, ok := c.Args[0].(*ast.BasicLit); ok && lit.Kind == token.STRING &&
		!strings.HasPrefix(lit.Value, "`") {
		// translate verbs inside the format literal
		inner := lit.Value[1 : len(lit.Value)-1]
		var b strings.Builder
		for i := 0; i < len(inner); i++ {
			if inner[i] == '%' && i+1 < len(inner) {
				switch inner[i+1] {
				case 's', 'v', 'd':
					b.WriteString("{}")
					i++
					continue
				case 'q':
					b.WriteString("{:?}")
					i++
					continue
				case 'x':
					b.WriteString("{:x}")
					i++
					continue
				case '%':
					b.WriteString("%")
					i++
					continue
				}
			}
			b.WriteByte(inner[i])
		}
		var rest []string
		for _, a := range c.Args[1:] {
			if identName(a) == "t" {
				rest = append(rest, "&mut *t")
				continue
			}
			rest = append(rest, tr.expr(a))
		}
		return "format!(\"" + b.String() + "\", " + strings.Join(rest, ", ") + ")"
	}
	return "format!(" + args + ")"
}

func (tr *translator) sprintfTo(c *ast.CallExpr, mac string) string {
	args := tr.args(c.Args, 0)
	return mac + "(" + args + ")"
}

// emitTRun emits t.Run(name, func(t *testing.T){...}) ->
// run_subtest(&mut t, name, |t| { ... }) writing straight to the output.
func (tr *translator) emitTRun(c *ast.CallExpr) {
	name := tr.expr(c.Args[0])
	var lit *ast.FuncLit
	if len(c.Args) > 1 {
		lit, _ = c.Args[1].(*ast.FuncLit)
	}
	fmt.Fprintf(&tr.out, "%srun_subtest(&mut t, %s, |t| {\n", tr.indent(), name)
	tr.depth++
	if lit != nil {
		body := tr.stripBoilerplate(lit.Body.List)
		tr.emitBlock(body)
	}
	tr.depth--
	tr.out.WriteString(tr.indent() + "});\n")
}

// composite translates Go composite literals.
func (tr *translator) composite(x *ast.CompositeLit) string {
	return tr.compositeAs(x, "")
}

// compositeAs translates a composite literal; expectedType supplies the Rust
// type path when Go elides the literal type (e.g. `{...}` inside `[]T{...}`).
func (tr *translator) compositeAs(x *ast.CompositeLit, expectedType string) string {
	if x.Type == nil {
		if expectedType != "" {
			var b strings.Builder
			b.WriteString(expectedType + " { ")
			for _, e := range x.Elts {
				if kv, ok := e.(*ast.KeyValueExpr); ok {
					b.WriteString(snake(identName(kv.Key)) + ": " + tr.expr(kv.Value) + ", ")
				} else {
					b.WriteString(tr.expr(e) + ", ")
				}
			}
			b.WriteString("..Default::default() }")
			return b.String()
		}
		note(tr.fset, x, "elided composite lit without context")
		return "Default::default()"
	}
	switch t := x.Type.(type) {
	case *ast.SelectorExpr:
		// &pkg.Type{...} -> pkg::Type { field: v, ..Default::default() }
		pkg := identName(t.X)
		path := tr.imports[pkg]
		if path == "" {
			path = pkg
		}
		var b strings.Builder
		b.WriteString(path + "::" + t.Sel.Name + " { ")
		for _, e := range x.Elts {
			if kv, ok := e.(*ast.KeyValueExpr); ok {
				b.WriteString(snake(identName(kv.Key)) + ": " + tr.expr(kv.Value) + ", ")
			} else {
				b.WriteString(tr.expr(e) + ", ")
			}
		}
		b.WriteString("..Default::default() }")
		return b.String()

	case *ast.Ident:
		var b strings.Builder
		b.WriteString(t.Name + " { ")
		for _, e := range x.Elts {
			if kv, ok := e.(*ast.KeyValueExpr); ok {
				b.WriteString(snake(identName(kv.Key)) + ": " + tr.expr(kv.Value) + ", ")
			} else {
				b.WriteString(tr.expr(e) + ", ")
			}
		}
		b.WriteString("..Default::default() }")
		return b.String()

	case *ast.ArrayType:
		var eltType string
		if st, ok := t.Elt.(*ast.StructType); ok {
			eltType = tr.anonStruct(st, x)
		} else {
			eltType = tr.elemRustType(t.Elt)
		}
		var parts []string
		for _, e := range x.Elts {
			if cl, ok := e.(*ast.CompositeLit); ok {
				parts = append(parts, tr.compositeAs(cl, eltType))
			} else {
				parts = append(parts, tr.expr(e))
			}
		}
		return "vec![" + strings.Join(parts, ", ") + "]"

	case *ast.MapType:
		_, isSlice := t.Value.(*ast.ArrayType)
		var parts []string
		for _, e := range x.Elts {
			if kv, ok := e.(*ast.KeyValueExpr); ok {
				var v string
				if cl, ok2 := kv.Value.(*ast.CompositeLit); ok2 && cl.Type == nil {
					if isSlice {
						v = tr.exprSlice(cl)
					} else {
						v = tr.compositeAs(cl, tr.elemRustType(t.Value))
					}
				} else {
					v = tr.expr(kv.Value)
				}
				parts = append(parts, "("+tr.expr(kv.Key)+", "+v+")")
			}
		}
		return "vec![" + strings.Join(parts, ", ") + "].into_iter().collect::<FxHashMap<_, _>>()"
	}
	note(tr.fset, x, "composite lit type %T", x.Type)
	return "/* lit */"
}

// elemRustType renders the element type of a slice/array literal for nested
// elided composites (`pkg.T`, `*pkg.T`, `T`).
func (tr *translator) elemRustType(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	switch t := e.(type) {
	case *ast.SelectorExpr:
		pkg := identName(t.X)
		path := tr.imports[pkg]
		if path == "" {
			path = pkg
		}
		return path + "::" + t.Sel.Name
	case *ast.Ident:
		return t.Name
	}
	return ""
}

// exprSlice renders an elided `{a, b}` composite as `vec![a, b]`.
func (tr *translator) exprSlice(cl *ast.CompositeLit) string {
	var parts []string
	for _, e := range cl.Elts {
		parts = append(parts, tr.expr(e))
	}
	return "vec![" + strings.Join(parts, ", ") + "]"
}

// anonStruct synthesizes a named Rust struct for a Go `[]struct{...}` literal
// and returns its name. Field types are guessed from the element values.
func (tr *translator) anonStruct(st *ast.StructType, lit *ast.CompositeLit) string {
	tr.anonCounter++
	name := fmt.Sprintf("anon_%d", tr.anonCounter)

	// union of field names -> guessed Rust types
	type fv struct {
		rname string
		rtype string
	}
	fields := map[string]*fv{}
	var order []string
	guess := func(v ast.Expr) string {
		switch e := v.(type) {
		case *ast.BasicLit:
			switch e.Kind {
			case token.STRING:
				return "&'static str"
			case token.INT:
				return "i64"
			case token.FLOAT:
				return "f64"
			case token.CHAR:
				return "char"
			}
		case *ast.Ident:
			if e.Name == "true" || e.Name == "false" {
				return "bool"
			}
		case *ast.CompositeLit:
			return "serde_json::Value"
		case *ast.UnaryExpr:
			if e.Op == token.AND {
				return "&'static str"
			}
		}
		return "serde_json::Value"
	}
	for _, e := range lit.Elts {
		cl, ok := e.(*ast.CompositeLit)
		if !ok {
			continue
		}
		for _, kv := range cl.Elts {
			k, ok := kv.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			fn := identName(k.Key)
			if fn == "" {
				continue
			}
			rn := snake(fn)
			if _, seen := fields[rn]; !seen {
				fields[rn] = &fv{rname: rn, rtype: guess(k.Value)}
				order = append(order, rn)
			} else if fields[rn].rtype == "" {
				fields[rn].rtype = guess(k.Value)
			}
		}
	}
	// fall back to Go field decl types when no literal field observed
	if st.Fields != nil {
		for _, f := range st.Fields.List {
			for _, n := range f.Names {
				rn := snake(n.Name)
				if _, seen := fields[rn]; !seen {
					fields[rn] = &fv{rname: rn, rtype: "serde_json::Value"}
					order = append(order, rn)
				}
			}
		}
	}

	var b strings.Builder
	b.WriteString("#[derive(Default, Clone, Debug)]\nstruct " + name + " {\n")
	for _, rn := range order {
		fmt.Fprintf(&b, "\t%s: %s,\n", rn, fields[rn].rtype)
	}
	b.WriteString("}")
	tr.pendingDecls = append(tr.pendingDecls, b.String())
	return name
}
