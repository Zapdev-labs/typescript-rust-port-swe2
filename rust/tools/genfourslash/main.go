// genfourslash translates Go fourslash *_test.go files into Rust #[test]
// functions. It is intentionally pattern-driven rather than a general Go→Rust
// compiler: the corpus (~4.3k files) uses a small, regular vocabulary —
// fourslash.NewFourslash, f.Verify*/GoTo*/Insert calls with `t` as the first
// arg, option struct literals, raw-string test content, t.Run subtests, and
// t.Parallel/defer boilerplate.
//
// Usage:
//   go run ./tools/genfourslash -src <file|dir> -out <dir> [-list report.txt]
//
// Output: one .rs file per Go file under <out>, plus a report of
// untranslated constructs for manual review.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"unicode"
)

var (
	flagSrc  = flag.String("src", "", "Go file or directory of *_test.go files")
	flagOut  = flag.String("out", "", "output directory for .rs files")
	flagList = flag.String("list", "", "optional report file")
)

// unresolved collects constructs the translator could not handle so they can
// be fixed by hand or by extending the translator.
var unresolved []string

func note(fset *token.FileSet, node ast.Node, format string, args ...any) {
	pos := fset.Position(node.Pos())
	unresolved = append(unresolved, fmt.Sprintf("%s: %s", pos, fmt.Sprintf(format, args...)))
}

func main() {
	flag.Parse()
	if *flagSrc == "" || *flagOut == "" {
		fmt.Fprintln(os.Stderr, "usage: genfourslash -src <file|dir> -out <dir> [-list report]")
		os.Exit(2)
	}

	var files []string
	info, err := os.Stat(*flagSrc)
	must(err)
	if info.IsDir() {
		ents, err := os.ReadDir(*flagSrc)
		must(err)
		for _, e := range ents {
			if strings.HasSuffix(e.Name(), "_test.go") {
				files = append(files, filepath.Join(*flagSrc, e.Name()))
			}
		}
	} else {
		files = []string{*flagSrc}
	}
	must(os.MkdirAll(*flagOut, 0o755))

	converted, skipped := 0, 0
	for _, f := range files {
		if err := translateFile(f, *flagOut); err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", f, err)
			skipped++
			continue
		}
		converted++
	}
	fmt.Printf("converted %d files, %d failed, %d unresolved constructs\n",
		converted, skipped, len(unresolved))
	if *flagList != "" {
		must(os.WriteFile(*flagList, []byte(strings.Join(unresolved, "\n")+"\n"), 0o644))
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// ----------------------------------------------------------------------------
// file-level translation
// ----------------------------------------------------------------------------

type translator struct {
	fset *token.FileSet
	src  []byte // source text for raw literal extraction
	out  strings.Builder
	// imports maps Go package qualifier -> Rust path prefix.
	imports map[string]string
	depth   int
	// pendingDecls accumulates synthesized decls (anonymous-struct cases)
	// that must precede the current statement.
	pendingDecls []string
	anonCounter  int
	// localStructs: fn-local Go `type X struct{...}` names -> ordered field list.
	localStructs map[string][]string
}

// flushDecls emits synthesized declarations pending before the next stmt.
func (tr *translator) flushDecls() {
	for _, s := range tr.pendingDecls {
		for _, line := range strings.Split(s, "\n") {
			if line != "" {
				tr.out.WriteString(tr.indent() + line + "\n")
			}
		}
	}
	tr.pendingDecls = tr.pendingDecls[:0]
}

func translateFile(path, outDir string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	tr := &translator{
		fset: fset,
		src:  src,
		localStructs: map[string][]string{},
		imports: map[string]string{
			"fourslash": "tsc_fourslash",
			"testutil":  "tsc_testutil",
			"util":      "tsc_fourslash::testsutil", // fourslash/tests/util package alias
			"lsutil":    "tsc_lsutil",
			"lsproto":   "tsc_lsproto",
			"ls":        "tsc_ls",
			"core":      "tsc_core",
			"contentmappertest": "tsc_testutil::contentmappertest",
			"modulespecifiers":  "tsc_modulespecifiers",
			"tspath":    "tsc_tspath",
			"baseline":  "tsc_testutil::baseline",
			"stringutil": "tsc_stringutil",
			"lsconv":    "tsc_lsconv",
			"stringtestutil": "tsc_testutil::stringtestutil",
			"assert":   "", // gotest.tools asserts -> assert!/assert_eq!
			"fourslashUtil":  "tsc_fourslash::testsutil",
			"fourslash_util": "tsc_fourslash::testsutil",
			"fmt":       "", // mapped via builtins
			"testing":   "",
			"strings":   "",
			"slices":    "",
		},
	}

	base := strings.TrimSuffix(filepath.Base(path), ".go")
	tr.out.WriteString("// @generated by genfourslash from tsc/internal/fourslash/tests/" + filepath.Base(path) + "\n")
	tr.out.WriteString("#![allow(unused, non_snake_case)]\n\n")
	tr.out.WriteString("use crate::gen_support::*;\n")
	tr.out.WriteString("use tsc_fourslash::*;\n\n")

	nTests := 0
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv != nil {
			continue
		}
		if !strings.HasPrefix(fn.Name.Name, "Test") {
			// helper function — translate it too
			tr.emitFunc(fn)
			continue
		}
		tr.emitTest(fn)
		nTests++
	}
	if nTests == 0 {
		return fmt.Errorf("no test functions")
	}

	outPath := filepath.Join(outDir, base+".rs")
	return os.WriteFile(outPath, []byte(tr.out.String()), 0o644)
}

// ----------------------------------------------------------------------------
// naming
// ----------------------------------------------------------------------------

var (
	camelBoundary = regexp.MustCompile(`([a-z0-9])([A-Z])`)
	acronymTail   = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
)

// snake converts CamelCase/mixed names to snake_case.
func snake(s string) string {
	s = camelBoundary.ReplaceAllString(s, "${1}_${2}")
	// also split acronym tails: HTTPServer -> http_server (Xx boundary)
	s = acronymTail.ReplaceAllString(s, "${1}_${2}")
	return strings.ToLower(s)
}

// screaming converts Go exported constants (e.g. TSTrue, QuotePreferenceSingle)
// to SCREAMING_SNAKE.
func screaming(s string) string {
	return strings.ToUpper(snake(s))
}

// ----------------------------------------------------------------------------
// function emission
// ----------------------------------------------------------------------------

// emitTest emits `#[test] fn name() { run_test_body(|| { <body> }) }`.
func (tr *translator) emitTest(fn *ast.FuncDecl) {
	name := snake(strings.TrimPrefix(fn.Name.Name, "Test"))
	fmt.Fprintf(&tr.out, "#[test]\nfn %s() {\n", name)
	tr.depth++
	// strip leading t.Parallel()/defer RecoverAndFail boilerplate
	body := tr.stripBoilerplate(fn.Body.List)
	tr.out.WriteString("\trun_test(|t| {\n")
	tr.depth++
	tr.emitBlock(body)
	tr.depth--
	tr.out.WriteString("\t});\n")
	tr.depth--
	tr.out.WriteString("}\n\n")
}

// emitFunc emits a non-Test helper as a plain fn. `t *testing.T` params map to
// `t: &mut TestHandle`; `f *fourslash.FourslashTest` to &mut FourslashTest.
func (tr *translator) emitFunc(fn *ast.FuncDecl) {
	var params []string
	if fn.Type.Params != nil {
		for _, p := range fn.Type.Params.List {
			typ := tr.paramType(p.Type)
			for _, n := range p.Names {
				params = append(params, fmt.Sprintf("%s: %s", rustIdent(n.Name), typ))
			}
		}
	}
	fmt.Fprintf(&tr.out, "fn %s(%s) {\n", rustIdent(fn.Name.Name), strings.Join(params, ", "))
	tr.depth++
	tr.emitBlock(fn.Body.List)
	tr.depth--
	tr.out.WriteString("}\n\n")
}

func (tr *translator) paramType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		if sel, ok := t.X.(*ast.SelectorExpr); ok {
			pkg := identName(sel.X)
			if pkg == "testing" && sel.Sel.Name == "T" {
				return "&mut TestHandle"
			}
			if pkg == "fourslash" && sel.Sel.Name == "FourslashTest" {
				return "&mut FourslashTest"
			}
		}
		return "&mut " + tr.expr(t.X)
	case *ast.SelectorExpr:
		return tr.expr(t)
	case *ast.Ident:
		return tr.expr(t)
	case *ast.ArrayType:
		return "Vec<" + tr.expr(t.Elt) + ">"
	case *ast.Ellipsis:
		return "&[" + tr.expr(t.Elt) + "]"
	}
	note(tr.fset, e, "unhandled param type %T", e)
	return "/* ? */"
}

// emitLocalStruct emits `type X struct{...}` (a fn-local Go type) as a Rust
// struct decl; positional `X{a, b}` literals then resolve field names.
func (tr *translator) emitLocalStruct(name string, st *ast.StructType) {
	var fields []string
	tr.localStructs[name] = fields
	var b strings.Builder
	b.WriteString("#[derive(Default, Clone, Debug)]\nstruct " + name + " {\n")
	for _, f := range st.Fields.List {
		typ := tr.localFieldType(f.Type)
		for _, n := range f.Names {
			rn := fieldName(n.Name)
			tr.localStructs[name] = append(tr.localStructs[name], rn)
			fmt.Fprintf(&b, "\t%s: %s,\n", rn, typ)
		}
	}
	b.WriteString("}")
	tr.pendingDecls = append(tr.pendingDecls, b.String())
}

// localFieldType maps Go field types in local struct decls to Rust types.
func (tr *translator) localFieldType(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		return "Option<" + tr.localFieldType(s.X) + ">"
	}
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "String"
		case "bool":
			return "bool"
		case "int", "int32":
			return "i32"
		case "int64":
			return "i64"
		case "float64":
			return "f64"
		}
		return tr.expr(e)
	case *ast.SelectorExpr:
		return tr.expr(e)
	case *ast.ArrayType:
		return "Vec<" + tr.localFieldType(t.Elt) + ">"
	}
	return "serde_json::Value"
}

// stripBoilerplate removes `t.Parallel()` and `defer testutil.RecoverAndFail(...)`
// leading statements (RecoverAndFail is subsumed by the run_test wrapper).
func (tr *translator) stripBoilerplate(stmts []ast.Stmt) []ast.Stmt {
	var out []ast.Stmt
	for _, s := range stmts {
		if es, ok := s.(*ast.ExprStmt); ok && tr.isCall(es.X, "t", "Parallel") {
			continue
		}
		if ds, ok := s.(*ast.DeferStmt); ok {
			if tr.isCall(ds.Call, "testutil", "RecoverAndFail") ||
				tr.isCall(ds.Call, "util", "RecoverAndFail") {
				continue
			}
			// `defer done()` -> RAII; drop (guard owns cleanup)
			if id, ok := ds.Call.Fun.(*ast.Ident); ok && strings.HasPrefix(id.Name, "done") {
				continue
			}
		}
		out = append(out, s)
	}
	return out
}

func identName(e ast.Expr) string {
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// isCall reports whether e is `pkg.name(...)` (name == "" matches a bare call).
func (tr *translator) isCall(e ast.Expr, pkg, name string) bool {
	call, ok := e.(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	if name != "" && sel.Sel.Name != name {
		return false
	}
	return identName(sel.X) == pkg
}

// ----------------------------------------------------------------------------
// statements
// ----------------------------------------------------------------------------

func (tr *translator) indent() string { return strings.Repeat("\t", tr.depth) }

func (tr *translator) emitBlock(stmts []ast.Stmt) {
	for _, s := range stmts {
		tr.emitStmt(s)
	}
}

func (tr *translator) emitStmt(s ast.Stmt) {
	tr.flushDecls()
	switch st := s.(type) {
	case *ast.ExprStmt:
		if call, ok := st.X.(*ast.CallExpr); ok {
			if sel, ok2 := call.Fun.(*ast.SelectorExpr); ok2 &&
				identName(sel.X) == "t" && sel.Sel.Name == "Run" {
				tr.emitTRun(call)
				return
			}
		}
		tr.out.WriteString(tr.indent() + tr.expr(st.X) + ";\n")

	case *ast.DeclStmt:
		decl, ok := st.Decl.(*ast.GenDecl)
		if !ok {
			note(tr.fset, s, "decl stmt %T", st.Decl)
			return
		}
		for _, spec := range decl.Specs {
			switch sp := spec.(type) {
			case *ast.TypeSpec:
				if st2, ok2 := sp.Type.(*ast.StructType); ok2 {
					tr.emitLocalStruct(sp.Name.Name, st2)
				} else {
					note(tr.fset, spec, "type decl %T", sp.Type)
				}
			case *ast.ValueSpec:
				for i, n := range sp.Names {
					var init string
					if i < len(sp.Values) {
						init = tr.expr(sp.Values[i])
					} else {
						init = "Default::default()"
					}
					kw := "let"
					if decl.Tok == token.CONST {
						kw = "let" // Go consts are immutable; `let` suffices (const only used for literals)
					}
					fmt.Fprintf(&tr.out, "%s%s %s = %s;\n", tr.indent(), kw, rustIdent(n.Name), init)
				}
			default:
				note(tr.fset, spec, "decl spec %T", spec)
			}
		}

	case *ast.AssignStmt:
		if len(st.Lhs) == 1 && len(st.Rhs) == 1 {
			lhs := tr.expr(st.Lhs[0])
			rhsExpr := st.Rhs[0]
			if st.Tok == token.DEFINE {
				if u, ok := rhsExpr.(*ast.UnaryExpr); ok && u.Op == token.AND {
					if _, ok2 := u.X.(*ast.CompositeLit); ok2 {
						rhsExpr = u.X // &T{...} -> owned T{...}
					}
				}
			}
			rhs := tr.expr(rhsExpr)
			switch st.Tok {
			case token.DEFINE:
				fmt.Fprintf(&tr.out, "%slet mut %s = %s;\n", tr.indent(), lhs, rhs)
			case token.ASSIGN:
				if ix, ok := st.Lhs[0].(*ast.IndexExpr); ok {
					fmt.Fprintf(&tr.out, "%s%s.insert(%s, %s);\n", tr.indent(),
						tr.expr(ix.X), tr.expr(ix.Index), rhs)
					return
				}
				fmt.Fprintf(&tr.out, "%s%s = %s;\n", tr.indent(), lhs, rhs)
			case token.ADD_ASSIGN:
				fmt.Fprintf(&tr.out, "%s%s += %s;\n", tr.indent(), lhs, rhs)
			default:
				note(tr.fset, s, "assign op %s", st.Tok)
			}
			return
		}
		if st.Tok == token.DEFINE && len(st.Rhs) == 1 {
			// `f, done := fourslash.NewFourslash(...)` — done is a Drop-guard;
			// the port returns just FourslashTest.
			var names []string
			for _, l := range st.Lhs {
				names = append(names, rustIdent(tr.expr(l)))
			}
			rhs := tr.expr(st.Rhs[0])
			if strings.HasPrefix(rhs, "tsc_fourslash::new_fourslash") && len(names) == 2 {
				fmt.Fprintf(&tr.out, "%slet mut %s = %s;\n", tr.indent(), names[0], rhs)
				return
			}
			fmt.Fprintf(&tr.out, "%slet (%s) = %s;\n", tr.indent(), strings.Join(mutNames(names), ", "), rhs)
			return
		}
		note(tr.fset, s, "multi-assign %d = %d", len(st.Lhs), len(st.Rhs))

	case *ast.IncDecStmt:
		op := "++"
		if st.Tok == token.DEC {
			op = "--"
		}
		fmt.Fprintf(&tr.out, "%s%s %s;\n", tr.indent(), tr.expr(st.X), op)

	case *ast.IfStmt:
		tr.emitIf(st)

	case *ast.ForStmt:
		fmt.Fprintf(&tr.out, "%sfor {\n", tr.indent()) // placeholder; refined below
		note(tr.fset, st, "C-style for")

	case *ast.RangeStmt:
		key, val := "_", "_"
		if st.Key != nil {
			key = rustIdent(tr.expr(st.Key))
		}
		if st.Value != nil {
			val = rustIdent(tr.expr(st.Value))
		}
		_ = key // Go always has key when value is used
		if st.Value != nil {
			fmt.Fprintf(&tr.out, "%sfor %s in %s {\n", tr.indent(), val, tr.expr(st.X))
		} else {
			fmt.Fprintf(&tr.out, "%sfor %s in %s {\n", tr.indent(), key, tr.expr(st.X))
		}
		tr.depth++
		tr.emitBlock(st.Body.List)
		tr.depth--
		tr.out.WriteString(tr.indent() + "}\n")

	case *ast.ReturnStmt:
		if len(st.Results) == 0 {
			tr.out.WriteString(tr.indent() + "return;\n")
		} else {
			var parts []string
			for _, r := range st.Results {
				parts = append(parts, tr.expr(r))
			}
			fmt.Fprintf(&tr.out, "%sreturn %s;\n", tr.indent(), strings.Join(parts, ", "))
		}

	case *ast.DeferStmt:
		// handled by stripBoilerplate for known forms; others are unhandled
		if tr.isCall(st.Call, "testutil", "RecoverAndFail") ||
			tr.isCall(st.Call, "util", "RecoverAndFail") {
			return
		}
		if id, ok := st.Call.Fun.(*ast.Ident); ok && strings.HasPrefix(id.Name, "done") {
			return
		}
		note(tr.fset, st, "unhandled defer")

	case *ast.GoStmt:
		note(tr.fset, st, "go statement")

	case *ast.SwitchStmt:
		tr.emitSwitch(st)

	case *ast.BranchStmt:
		kw := "break"
		if st.Tok == token.CONTINUE {
			kw = "continue"
		}
		tr.out.WriteString(tr.indent() + kw + ";\n")

	case *ast.BlockStmt:
		tr.out.WriteString(tr.indent() + "{\n")
		tr.depth++
		tr.emitBlock(st.List)
		tr.depth--
		tr.out.WriteString(tr.indent() + "}\n")

	case *ast.LabeledStmt:
		tr.emitStmt(st.Stmt)

	default:
		note(tr.fset, s, "unhandled stmt %T", s)
	}
}

func (tr *translator) emitIf(st *ast.IfStmt) {
	cond := tr.expr(st.Cond)
	tr.out.WriteString(tr.indent() + "if " + cond + " {\n")
	tr.depth++
	tr.emitBlock(st.Body.List)
	tr.depth--
	if st.Else == nil {
		tr.out.WriteString(tr.indent() + "}\n")
		return
	}
	tr.out.WriteString(tr.indent() + "} else ")
	switch e := st.Else.(type) {
	case *ast.BlockStmt:
		tr.out.WriteString("{\n")
		tr.depth++
		tr.emitBlock(e.List)
		tr.depth--
		tr.out.WriteString(tr.indent() + "}\n")
	case *ast.IfStmt:
		tr.emitIf(e)
	}
}

func (tr *translator) emitSwitch(st *ast.SwitchStmt) {
	fmt.Fprintf(&tr.out, "%smatch %s {\n", tr.indent(), tr.expr(st.Tag))
	tr.depth++
	for _, c := range st.Body.List {
		cc := c.(*ast.CaseClause)
		if cc.List == nil {
			tr.out.WriteString(tr.indent() + "_ => {\n")
		} else {
			var pats []string
			for _, e := range cc.List {
				pats = append(pats, tr.expr(e))
			}
			tr.out.WriteString(tr.indent() + strings.Join(pats, " | ") + " => {\n")
		}
		tr.depth++
		tr.emitBlock(cc.Body)
		tr.depth--
		tr.out.WriteString(tr.indent() + "}\n")
	}
	tr.depth--
	tr.out.WriteString(tr.indent() + "}\n")
}

// ----------------------------------------------------------------------------
// expressions
// ----------------------------------------------------------------------------

func (tr *translator) expr(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Ident:
		return rustIdent(x.Name)

	case *ast.BasicLit:
		return tr.lit(x)

	case *ast.SelectorExpr:
		return tr.selector(x)

	case *ast.CallExpr:
		return tr.call(x)

	case *ast.StarExpr:
		return "(*" + tr.expr(x.X) + ").clone()"

	case *ast.UnaryExpr:
		switch x.Op {
		case token.AND:
			if _, ok := x.X.(*ast.CompositeLit); ok {
				return "&" + tr.expr(x.X) // &T{} -> &T{} in arg position
			}
			return "Some(" + tr.expr(x.X) + ".clone())" // &var -> *T -> Option<T>
		case token.NOT:
			return "!" + tr.expr(x.X)
		case token.SUB:
			return "-" + tr.expr(x.X)
		}
		return x.Op.String() + tr.expr(x.X)

	case *ast.BinaryExpr:
		if x.Op == token.ADD && tr.isConcat(x) {
			return "format!(\"{}{}\", " + tr.expr(x.X) + ", " + tr.expr(x.Y) + ")"
		}
		return tr.expr(x.X) + " " + x.Op.String() + " " + tr.expr(x.Y)

	case *ast.ParenExpr:
		return "(" + tr.expr(x.X) + ")"

	case *ast.CompositeLit:
		return tr.composite(x)

	case *ast.IndexExpr:
		if c, ok := x.X.(*ast.CallExpr); ok {
			if fs, ok2 := c.Fun.(*ast.SelectorExpr); ok2 &&
				(fs.Sel.Name == "Ranges" || fs.Sel.Name == "Markers" ||
					snake(fs.Sel.Name) == "ranges" || snake(fs.Sel.Name) == "markers") {
				return tr.expr(x.X) + "[" + tr.expr(x.Index) + "].clone()"
			}
		}
		return tr.expr(x.X) + "[" + tr.expr(x.Index) + "]"

	case *ast.SliceExpr:
		return tr.expr(x.X) + ".slice"

	case *ast.TypeAssertExpr:
		// x.(bool)/x.(string) on `any` map values -> as_bool()/as_str() guesses.
		tname := tr.expr(x.Type)
		fn := "as_" + snake(tname)
		return tr.expr(x.X) + "." + fn + "()"

	case *ast.FuncLit:
		var params []string
		if x.Type.Params != nil {
			for _, p := range x.Type.Params.List {
				for _, n := range p.Names {
					params = append(params, rustIdent(n.Name))
				}
			}
		}
		tr.out.WriteString("|")
		tr.out.WriteString(strings.Join(params, ", "))
		tr.out.WriteString("| {\n")
		tr.depth++
		tr.emitBlock(x.Body.List)
		tr.depth--
		tr.out.WriteString(tr.indent() + "}")
		return "" // caller emitted inline — signal via sentinel
	}
	note(tr.fset, e, "unhandled expr %T", e)
	return "/* ? */"
}

// isConcat reports whether the `+` expression involves a string literal
// (or another concat), meaning it is string concatenation, not arithmetic.
func (tr *translator) isConcat(x *ast.BinaryExpr) bool {
	if x.Op != token.ADD {
		return false
	}
	if lit, ok := x.X.(*ast.BasicLit); ok && lit.Kind == token.STRING {
		return true
	}
	if lit, ok := x.Y.(*ast.BasicLit); ok && lit.Kind == token.STRING {
		return true
	}
	if bx, ok := x.X.(*ast.BinaryExpr); ok && tr.isConcat(bx) {
		return true
	}
	if bx, ok := x.Y.(*ast.BinaryExpr); ok && tr.isConcat(bx) {
		return true
	}
	return false
}

// lit translates a Go literal to its Rust form.
func (tr *translator) lit(b *ast.BasicLit) string {
	switch b.Kind {
	case token.STRING:
		raw := b.Value
		if strings.HasPrefix(raw, "`") {
			return rustRawString(raw[1 : len(raw)-1])
		}
		// interpreted string — emit as Rust escaped literal (Go and Rust
		// share most escapes; keep it verbatim).
		return raw
	case token.CHAR:
		return b.Value
	case token.INT, token.FLOAT:
		return b.Value
	}
	return b.Value
}

// rustRawString wraps s in r#"..."# with enough # to be safe.
func rustRawString(s string) string {
	for n := 0; n < 8; n++ {
		h := strings.Repeat("#", n)
		if !strings.Contains(s, "\""+h) {
			return "r" + h + "\"" + s + "\"" + h
		}
	}
	return "\"" + strings.ReplaceAll(s, "\"", "\\\"") + "\""
}

