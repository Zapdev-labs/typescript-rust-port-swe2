#!/usr/bin/env bash
# Regenerate the fourslash test suite: Go tests -> crates/fourslash/tests/gen*.
set -euo pipefail
GEN=/home/dih/TypeScript/rust/tools/genfourslash/genfourslash
SRC=${1:-/home/dih/TypeScript/tsc/internal/fourslash/tests}
OUT=/home/dih/TypeScript/rust/crates/fourslash/tests
CHUNKS=${CHUNKS:-8}
mkdir -p "$OUT/gen"
"$GEN" -src "$SRC" -out "$OUT/gen" -list "$OUT/gen-report.txt"
files=$(cd "$OUT/gen" && ls *.rs | sort)
i=0
declare -a mods
for c in $(seq 0 $((CHUNKS-1))); do mods[$c]=""; done
for f in $files; do
  m="${f%.rs}"
  m="${m//-/_}"
  m="${m//@/_}"
  m="${m//./_}"
  mods[$((i % CHUNKS))]+="#[path = \"gen/${f}\"] mod ${m};\n"
  i=$((i+1))
done
for c in $(seq 0 $((CHUNKS-1))); do
  {
    echo "// @generated by run.sh -- fourslash suite chunk $c"
    echo "mod gen_support;"
    printf "%b" "${mods[$c]}"
  } > "$OUT/gen_${c}.rs"
done
echo "wrote $i test modules across $CHUNKS targets"
