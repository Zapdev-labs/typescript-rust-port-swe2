def func_body(name):
    i = src.index('func %s(' % name)
    j = src.index('{', i)
    depth = 0
    k = j
    while True:
        if src[k] == '{': depth += 1
        elif src[k] == '}': depth -= 1
        if depth == 0: break
        k += 1
    return src[j + 1:k]

