# ---------------------------------------------------------------------------
# Go -> Rust type mapping
# ---------------------------------------------------------------------------

GO_PRIMS = {
    "string": "String",
    "bool": "bool",
    "int32": "i32",
    "uint32": "u32",
    "float64": "f64",
    "byte": "u8",
    "any": "serde_json::Value",
    "struct{}": "EmptyObject",
}

# go type expr -> rust type for a value (no pointer context)
def vty(go):
    go = go.strip()
    if go in GO_PRIMS:
        return GO_PRIMS[go]
    m = re.fullmatch(r"\[(\d+)\]\w+", go)
    if m:
        return f"[u32; {m.group(1)}]"
    if go.startswith("[]"):
        return f"Vec<{vty(go[2:].lstrip('*'))}>"
    if go.startswith("map["):
        k, _, v = go[4:].partition("]")
        return f"BTreeMap<{vty(k)}, {vty(v.lstrip('*'))}>"
    if go.startswith("*"):
        return f"Option<{vty(go[1:])}>"
    return go


def fty(go):
    """Field type -> (rust_type, go_nilable, is_interface).

    go_nilable=True drives structcodec's rejectNull; interface (`any`) is
    nilable-but-not-rejected.  Resolved structs use `res` layout instead.
    """
    go = go.strip()
    if go == "any":
        return ("serde_json::Value", "iface")
    if go.startswith("*"):
        return (f"Option<{vty(go[1:])}>", True)
    if go.startswith("[]") or go.startswith("map["):
        return (f"Option<{vty(go)}>", True)
    return (vty(go), False)


def rty_resolved(go):
    """Field type inside a Resolved* struct (slices/maps are concrete)."""
    go = go.strip()
    if go.startswith("*"):
        return (f"Option<{vty(go[1:])}>", True)
    return (vty(go), go in ("string",) or go.startswith("[]") or go.startswith("map["))


def snake(name):
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = s.lower()
    if s in (
        "type", "ref", "self", "mod", "crate", "super", "match", "box",
        "move", "fn", "where", "loop", "enum", "impl", "use",
    ):
        s = s + "_"
    return s


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def doc_rs(lines, indent=""):
    out = []
    for ln in lines:
        out.append(indent + "///" + ln[2:])
    return out


