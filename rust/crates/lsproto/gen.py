# ---------------------------------------------------------------------------

def main():
    src_path, dst = sys.argv[1], sys.argv[2]
    src = open(src_path).read()
    decls = parse_top(src)

    # --- collect per-type funcs ---
    funcs = {}
    for kind, payload in decls:
        if kind != "func":
            continue
        m = re.match(r"func \((\w+) \*?(\w+)\) (\w+)\(", payload)
        if m:
            body = payload[payload.index("{") + 1 : payload.rindex("}")]
            funcs.setdefault(m.group(2), {})[m.group(3)] = body

    # --- classify types ---
    enum_types = {}
    aliases = []
    structs = {}
    order = []
    for kind, payload in decls:
        if kind == "typealias":
            name, rest, doc = payload
            if name.startswith("StringLiteral"):
                order.append(("literal", name))
            elif rest in GO_PRIMS and rest != "any":
                enum_types[name] = (rest, doc)
                order.append(("type", name))
            else:
                aliases.append((name, rest, doc))
                order.append(("type", name))
        elif kind == "struct":
            structs[payload.name] = payload
            order.append(("struct", payload.name))

    # enum consts + method consts + Info vars
    enum_consts = {}
    method_consts = []
    infos = []
    for kind, payload in decls:
        if kind == "constblock":
            body, _ = payload
            for cm in re.finditer(r"(?m)^\s*(\w+)\s+(\w+)\s*=\s*(.+?)\s*$", body):
                cname, cty, cval = cm.groups()
                cval = cval.strip()
                if cty == "Method":
                    method_consts.append((cname, cval.strip('"')))
                elif cty in enum_types:
                    enum_consts.setdefault(cty, []).append(
                        (cname, cval[1:-1] if cval.startswith('"') else cval)
                    )
        elif kind == "var":
            line, _ = payload
            m = re.match(
                r"(\w+) = (RequestInfo|NotificationInfo)\[(.*?)\]\{Method: (\w+)\}",
                line,
            )
            if m:
                infos.append((m.group(2), m.group(1), m.group(3), m.group(4)))

    # union detection: marshalUnion(...) in MarshalJSONTo
    marshal_nullable = {}
    for typ, fns in funcs.items():
        mb = fns.get("MarshalJSONTo", "")
        m = re.search(r'marshalUnion\(o, enc, "[^"]*", (true|false)\)', mb)
        if m:
            marshal_nullable[typ] = m.group(1) == "true"

    literals = {}
    lit_docs = {}
    for typ, fns in funcs.items():
        if typ.startswith("StringLiteral"):
            mb = fns.get("MarshalJSONTo", "")
            literals[typ] = re.search(r'json\.Value\(`"(.*)"`\)', mb).group(1)
    for kind, payload in decls:
        if kind == "typealias" and payload[0].startswith("StringLiteral"):
            lit_docs[payload[0]] = payload[2]

    # --- emission ---
    out = [HEADER]

    emitted = set()

    for what, name in order:
        if name in emitted:
            continue
        if what == "struct":
            st = structs[name]
            if name in literals:
                continue  # emitted later with other literals
            if name in marshal_nullable:
                emitted.add(name)
                fields = []
                for f in st.fields:
                    fields.append((f.name, vty(f.goty.lstrip("*"))))
                u = parse_union_body(
                    name, fields, funcs[name]["UnmarshalJSONFrom"]
                )
                emit_union(u, name, fields, marshal_nullable[name], st.doc, out)
                continue
            if name == "Registration":
                emitted.add(name)
                emit_registration(st, funcs, out)
                continue
            fns = funcs.get(name, {})
            ub = fns.get("UnmarshalJSONFrom", "")
            if "unmarshalStruct" in ub:
                emitted.add(name)
                emit_struct(st, out, is_copyable(st.name, structs, enum_types, marshal_nullable))
                continue
            # lenient/default-codec struct (incl. struct{} placeholders)
            emitted.add(name)
            if not st.fields:
                out += doc_rs(st.doc)
                out.append(
                    "#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]"
                )
                out.append(f"pub struct {name} {{}}")
                out.append("")
            else:
                emit_lenient_struct(st, out)
            continue
        if what == "literal":
            emitted.add(name)  # emitted in the literals section below
            continue
        else:
            # type alias / enum base
            emitted.add(name)
            if name in enum_types:
                base, doc = enum_types[name]
                if base == "string":
                    emit_string_enum(name, enum_consts.get(name, []), doc, out)
                else:
                    emit_num_enum(
                        name, base, enum_consts.get(name, []),
                        "String" in funcs.get(name, {}), doc, out,
                    )
            else:
                for an, arest, adoc in aliases:
                    if an == name:
                        out += doc_rs(adoc)
                        out.append(f"pub type {an} = {vty(arest)};")
                        out.append("")
                        break

    # check nothing unemitted
    missing = [n for w, n in order if n not in emitted]
    if missing:
        raise RuntimeError(f"unemitted types: {missing}")

    # literals
    out.append("// String literal types — exact-value markers (StringLiteral*).\n")
    for name, val in literals.items():
        emit_literal(name, val, lit_docs.get(name, []), out)

    # method consts
    out.append("/// `const (MethodX Method = \"...\")` — LSP method names.\n")
    out.append("impl Method {")
    for cname, cval in method_consts:
        short = cname[len("Method"):] if cname.startswith("Method") else cname
        out.append(f"\t/// `{cname}`")
        out.append(f'\tpub const {short}: Method = Method(Cow::Borrowed("{esc(cval)}"));')
    out.append("}")
    out.append("")

    # Info vars
    for kind, name, params, methodc in infos:
        short = methodc[len("Method"):] if methodc.startswith("Method") else methodc
        cname = snake(name).upper()
        if kind == "RequestInfo":
            pt, rt = [x.strip() for x in params.split(",")]
            out.append(f"/// `var {name} = RequestInfo[{pt}, {rt}]{{Method: {methodc}}}`")
            out.append(
                f"pub const {cname}: RequestInfo<{vty(pt)}, {vty(rt)}> = RequestInfo::new(Method::{short});"
            )
        else:
            out.append(f"/// `var {name} = NotificationInfo[{params}]{{Method: {methodc}}}`")
            out.append(
                f"pub const {cname}: NotificationInfo<{vty(params.strip())}> = NotificationInfo::new(Method::{short});"
            )
        out.append("")

    # Resolve methods
    for typ, fns in funcs.items():
        for fn_name, body in fns.items():
            if fn_name.lower() != "resolve":
                continue
            target = re.search(r"return (Resolved\w+)\{", body).group(1)
            assigns = re.findall(r"(\w+):\s*(.+?),?\n", body)
            out.append(f"impl {typ} {{")
            out.append(f"\t/// `{typ}.Resolve()` — collapses optional fields into the resolved")
            out.append("\t/// view used internally after capabilities are negotiated.")
            out.append(f"\tpub fn resolve(__this: Option<&Self>) -> {target} {{")
            out.append("\t\tlet Some(__v) = __this else {")
            out.append(f"\t\t\treturn {target}::default();")
            out.append("\t\t};")
            out.append(f"\t\t{target} {{")
            src_fields = {f.name: f for f in structs[typ].fields}
            for tgt, expr in assigns:
                expr = expr.strip()
                m = re.fullmatch(r"derefOr\(v\.(\w+)\)", expr)
                if m:
                    sf = src_fields[m.group(1)]
                    inner = vty(sf.goty[1:])
                    if is_copyable(inner, structs, enum_types, marshal_nullable):
                        e = f"__v.{snake(m.group(1))}.unwrap_or_default()"
                    else:
                        e = f"__v.{snake(m.group(1))}.clone().unwrap_or_default()"
                    out.append(f"\t\t\t{snake(tgt)}: {e},")
                    continue
                m = re.fullmatch(r"v\.(\w+)\.resolve\(\)", expr)
                if m:
                    sub = vty(src_fields[m.group(1)].goty.lstrip("*"))
                    out.append(
                        f"\t\t\t{snake(tgt)}: {sub}::resolve(__v.{snake(m.group(1))}.as_ref()),"
                    )
                    continue
                m = re.fullmatch(r"v\.(\w+)", expr)
                if m:
                    sf = src_fields[m.group(1)]
                    rt, _ = fty(sf.goty)
                    if is_copyable(rt, structs, enum_types, marshal_nullable):
                        e = f"__v.{snake(m.group(1))}"
                    elif sf.goty.startswith("*"):
                        e = f"__v.{snake(m.group(1))}.clone()"
                    elif sf.goty.startswith("[]") or sf.goty.startswith("map["):
                        e = f"__v.{snake(m.group(1))}.clone().unwrap_or_default()"
                    else:
                        e = f"__v.{snake(m.group(1))}.clone()"
                    out.append(f"\t\t\t{snake(tgt)}: {e},")
                    continue
                out.append(f"\t\t\t{snake(tgt)}: {expr},")
            out.append("\t\t}")
            out.append("\t}")
            out.append("}")
            out.append("")

    # simple accessor methods: TextDocumentURI / TextDocumentPosition / GetLocation / GetLocations / Compare
    emit_methods(structs, funcs, enum_types, marshal_nullable, out)

    with open(dst, "w") as fh:
        fh.write("\n".join(out))


_PRIM_COPY = {"bool", "u32", "i32", "f64", "u8"}

# Types that never derive Copy: unions (emitted without Copy), plus the
# non-primitive leaf types above.
_NONCOPY_TYPES = ()


def is_copyable(name, structs, enum_types, unions=()):
    seen = set()

    def chk(n):
        n = n.strip()
        if n in _PRIM_COPY or n.startswith("[u32;"):
            return True
        if n in ("String", "serde_json::Value", "EmptyObject", "DocumentUri",
                 "URI", "Method", "NoParams", "Null") or n in unions:
            return False
        if n.startswith("Option<") and n.endswith(">"):
            return chk(n[7:-1])
        # A cycle means the emitted field ends up behind Box — not Copy.
        if n in seen:
            return False
        seen.add(n)
        if n in enum_types:
            return enum_types[n][0] in ("uint32", "int32", "byte", "float64")
        st = structs.get(n)
        if not st:
            return False
        return all(chk(fty(f.goty)[0]) for f in st.fields)
    return chk(name)


def emit_methods(structs, funcs, enum_types, marshal_nullable, out):
    def field_expr(typ, gofield):
        st = structs[typ]
        f = next(f for f in st.fields if f.name == gofield)
        rt, _ = fty(f.goty)
        if is_copyable(rt, structs, enum_types, marshal_nullable):
            return f"self.{snake(gofield)}"
        return f"self.{snake(gofield)}.clone()"

    for typ, fns in funcs.items():
        for name, body in fns.items():
            b = body.strip()
            if name == "TextDocumentURI":
                src = re.search(r"return s\.(\w+)\.(\w+)", b)
                out.append(f"impl {typ} {{")
                out.append("\t/// `func (s *X) TextDocumentURI() DocumentUri`")
                out.append("\tpub fn text_document_uri(&self) -> DocumentUri {")
                out.append(
                    f"\t\tself.{snake(src.group(1))}.{snake(src.group(2))}.clone()"
                )
                out.append("\t}")
                out.append("}")
                out.append("")
            elif name == "TextDocumentPosition":
                src = re.search(r"return s\.(\w+)", b)
                out.append(f"impl {typ} {{")
                out.append("\t/// `func (s *X) TextDocumentPosition() Position`")
                out.append("\tpub fn text_document_position(&self) -> Position {")
                out.append(f"\t\t{field_expr(typ, src.group(1))}")
                out.append("\t}")
                out.append("}")
                out.append("")
            elif name == "GetLocation":
                out.append(f"impl {typ} {{")
                out.append("\t/// `func (s X) GetLocation() Location`")
                out.append("\tpub fn get_location(&self) -> Location {")
                if re.fullmatch(r"return s", b):
                    out.append("\t\tself.clone()")
                else:
                    m = re.search(
                        r"return Location\{\s*\n\s*Uri:\s*s\.(\w+),\s*\n\s*Range:\s*s\.(\w+),\s*\n\s*\}",
                        b,
                    )
                    uf, rf = m.group(1), m.group(2)
                    out.append("\t\tLocation {")
                    out.append(f"\t\t\turi: {field_expr(typ, uf)},")
                    out.append(f"\t\t\trange: {field_expr(typ, rf)},")
                    out.append("\t\t}")
                out.append("\t}")
                out.append("}")
                out.append("")
            elif name == "GetLocations":
                src = re.search(r"return o\.(\w+)", b)
                if src is None:
                    src = re.search(r"return s\.(\w+)", b)
                out.append(f"impl {typ} {{")
                out.append("\t/// `func (o X) GetLocations() *[]Location`")
                out.append("\tpub fn get_locations(&self) -> Option<&Vec<Location>> {")
                out.append(f"\t\tself.{snake(src.group(1))}.as_ref()")
                out.append("\t}")
                out.append("}")
                out.append("")

    # Compare: hard-code the three known impls (position/range/textedit)
    out.append("impl Position {")
    out.append("\t/// `func (s *Position) Compare(other *Position) int`")
    out.append("\tpub fn compare(&self, other: &Position) -> i32 {")
    out.append("\t\tself.line.cmp(&other.line) as i32")
    out.append("\t\t\t* (self.line != other.line) as i32")
    out.append("\t\t\t+ self.character.cmp(&other.character) as i32")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append("impl Range {")
    out.append("\t/// `func (s *Range) Compare(other *Range) int`")
    out.append("\tpub fn compare(&self, other: &Range) -> i32 {")
    out.append("\t\tlet c = self.start.compare(&other.start);")
    out.append("\t\tif c != 0 {")
    out.append("\t\t\treturn c;")
    out.append("\t\t}")
    out.append("\t\tself.end.compare(&other.end)")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append("impl TextEdit {")
    out.append("\t/// `func (s *TextEdit) Compare(other *TextEdit) int`")
    out.append("\tpub fn compare(&self, other: &TextEdit) -> i32 {")
    out.append("\t\tlet c = self.range.compare(&other.range);")
    out.append("\t\tif c != 0 {")
    out.append("\t\t\treturn c;")
    out.append("\t\t}")
    out.append("\t\tmatch self.new_text.cmp(&other.new_text) {")
    out.append("\t\t\tstd::cmp::Ordering::Less => -1,")
    out.append("\t\t\tstd::cmp::Ordering::Equal => 0,")
    out.append("\t\t\tstd::cmp::Ordering::Greater => 1,")
    out.append("\t\t}")
    out.append("\t}")
    out.append("}")
    out.append("")


