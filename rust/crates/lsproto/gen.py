KIND = {
    "'n'": "b'n'", "'{'": "b'{'", "'['": "b'['", "'\"'": "b'\"'",
    "'0'": "b'0'", "'t'": "b't'", "'f'": "b'f'",
}


def parse_union_body(name, fields, body):
    u = {"kind": None, "cases": [], "try": [], "hk": None, "disc": None,
         "null_shortcircuit": 'string(data) == "null"' in body}

    if "scanDiscriminatedStruct" in body:
        u["kind"] = "discriminated"
        m = re.search(r'scanDiscriminatedStruct\(dec, "[^"]*", "([^"]*)"\)', body)
        arms = []
        for cm in re.finditer(
            r"case `([^`]*)`:\s*\n\s*return unmarshalDiscriminatedArm\(state, &o\.(\w+)\)",
            body,
        ):
            arms.append((cm.group(1), cm.group(2)))
        d = re.search(r"default:\s*\n\s*return (.*)", body).group(1)
        default = None if "invalidDiscriminator" in d else re.search(
            r"&o\.(\w+)", d).group(1)
        u["disc"] = (m.group(1), arms, default)
        return u

    if "PeekKind" in body:
        u["kind"] = "kindswitch"
        for cm in re.finditer(r"case ([^:]+):\n(.*?)(?=\n\tcase |\n\tdefault:|\n\t\})", body, re.S):
            kinds = [k.strip() for k in cm.group(1).split(",")]
            u["cases"].append((kinds, parse_case(name, cm.group(2))))
        return u

    if "jsonObjectHasKey" in body:
        u["kind"] = "haskey"
        u["hk"] = parse_haskey(name, body)
        return u

    if "json.Unmarshal(data" in body:
        u["kind"] = "tryarms"
        for am in re.finditer(
            r"var (v\w+) ([^;\n]+)\n\s*if err := json\.Unmarshal\(data, &\1\); err == nil \{\s*\n\s*o\.(\w+) = &\1",
            body,
        ):
            u["try"].append((am.group(3), am.group(2).strip()))
        return u

    raise RuntimeError(f"unclassified union body for {name}:\n{body}")


def parse_haskey(name, body):
    m = re.search(r"jsonObjectHasKey\(data, ([^)]*)\)", body)
    keys = re.findall(r'"([^"]*)"', m.group(1))
    arms = {}
    for am in re.finditer(
        r"case (\d+):\s*(?://[^\n]*)?\n\s*o\.(\w+) = new\(([^)]+)\)\s*\n\s*return json\.Unmarshal\(data, o\.\w+\)",
        body,
    ):
        arms[int(am.group(1))] = am.group(2)
    dm = re.search(r"default:\s*\n\s*o\.(\w+) = new", body)
    return (keys, arms, dm.group(1) if dm else None)


def parse_case(name, cb):
    cb = cb.strip()
    if re.fullmatch(r"_, err := dec\.ReadToken\(\)\s*\n\s*return err", cb):
        return ("null",)
    m = re.fullmatch(
        r"o\.(\w+) = new\(kind == 't'\)\s*\n\s*_, err := dec\.ReadToken\(\)\s*\n\s*return err",
        cb,
    )
    if m:
        return ("booltok", m.group(1))
    m = re.fullmatch(r"o\.(\w+) = new\(([^)]+)\)\s*\n\s*return json\.UnmarshalDecode\(dec, o\.\1\)", cb)
    if m:
        return ("decode", m.group(1), m.group(2).strip())
    if "dec.ReadValue()" in cb:
        if "jsonObjectHasKey" in cb:
            return ("haskey", parse_haskey(name, cb))
        arms = []
        for am in re.finditer(
            r"var (v\w+) ([^;\n]+)\n\s*if err := json\.Unmarshal\(data, &\1\); err == nil \{\s*\n\s*o\.(\w+) = &\1",
            cb,
        ):
            arms.append((am.group(3), am.group(2).strip()))
        if arms:
            return ("tryarms", arms)
    raise RuntimeError(f"unclassified case body for {name}: {cb!r}")


