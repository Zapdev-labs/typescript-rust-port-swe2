def emit_field_docs(f, out, indent="\t"):
    for ln in f.doc:
        out.append(indent + "///" + ln[2:])


def emit_union_decode(u, name, fieldty, out):
    """Emit the body of unmarshal_json_from for a union, given __data/__bytes."""
    if u["null_shortcircuit"]:
        out.append('\t\tif __bytes == b"null" {')
        out.append("\t\t\treturn Ok(());")
        out.append("\t\t}")

    if u["kind"] == "discriminated":
        disc, arms, default = u["disc"]
        out.append("\t\tif __bytes[0] != b'{' {")
        out.append("\t\t\treturn Err(err_not_object(__bytes[0]));")
        out.append("\t\t}")
        out.append(f'\t\tlet __disc = json_object_raw_field(__bytes, "{esc(disc)}");')
        out.append("\t\tmatch __disc.as_ref().map(|__v| __v.get()) {")
        for raw, field in arms:
            out.append(f'\t\t\tSome("{esc(raw)}") => {{')
            out.append(
                f"\t\t\t\tself.{snake(field)} = Some(serde_json::from_slice::<{fieldty[field]}>(__bytes)?);"
            )
            out.append("\t\t\t\treturn Ok(());")
            out.append("\t\t\t}")
        if default:
            out.append("\t\t\t_ => {")
            out.append(
                f"\t\t\t\tself.{snake(default)} = Some(serde_json::from_slice::<{fieldty[default]}>(__bytes)?);"
            )
            out.append("\t\t\t\treturn Ok(());")
            out.append("\t\t\t}")
        else:
            out.append("\t\t\tSome(__v) =>")
            out.append(
                f'\t\t\t\treturn Err(serde_json::Error::custom(format!("invalid {name} discriminator \\"{disc}\\": {{}}", __v))),'
            )
            out.append("\t\t\tNone =>")
            out.append(
                f'\t\t\t\treturn Err(serde_json::Error::custom("invalid {name}: missing discriminator \\"{disc}\\"")),'
            )
        out.append("\t\t}")
        out.append("\t\tOk(())")
        return

    if u["kind"] == "haskey":
        keys, arms, default = u["hk"]
        ks = ", ".join(f'"{esc(k)}"' for k in keys)
        out.append(f"\t\tmatch json_object_has_key(__bytes, &[{ks}]) {{")
        for idx in sorted(arms):
            out.append(f"\t\t\t{idx} => {{")
            out.append(
                f"\t\t\t\tself.{snake(arms[idx])} = Some(serde_json::from_slice::<{fieldty[arms[idx]]}>(__bytes)?);"
            )
            out.append("\t\t\t\treturn Ok(());")
            out.append("\t\t\t}")
        if default:
            out.append("\t\t\t_ => {")
            out.append(
                f"\t\t\t\tself.{snake(default)} = Some(serde_json::from_slice::<{fieldty[default]}>(__bytes)?);"
            )
            out.append("\t\t\t\treturn Ok(());")
            out.append("\t\t\t}")
        else:
            out.append("\t\t\t_ => {}")
        out.append("\t\t}")
        out.append(f'\t\tErr(err_invalid_value("{name}", __data.get()))')
        return

    if u["kind"] == "tryarms":
        for field, goty in u["try"]:
            out.append(
                f"\t\tif let Ok(__v) = serde_json::from_slice::<{vty(goty)}>(__bytes) {{"
            )
            out.append(f"\t\t\tself.{snake(field)} = Some(__v);")
            out.append("\t\t\treturn Ok(());")
            out.append("\t\t}")
        out.append(f'\t\tErr(err_invalid_value("{name}", __data.get()))')
        return

    # kindswitch
    out.append("\t\tmatch norm_kind(__bytes[0]) {")
    for kinds, action in u["cases"]:
        pats = " | ".join(KIND[k] for k in kinds)
        out.append(f"\t\t\t{pats} => {{")
        a = action[0]
        if a == "null":
            out.append("\t\t\t\treturn Ok(());")
        elif a == "booltok":
            out.append(f"\t\t\t\tself.{snake(action[1])} = Some(__bytes[0] == b't');")
            out.append("\t\t\t\treturn Ok(());")
        elif a == "decode":
            out.append(
                f"\t\t\t\tself.{snake(action[1])} = Some(serde_json::from_slice::<{vty(action[2])}>(__bytes)?);"
            )
            out.append("\t\t\t\treturn Ok(());")
        elif a == "haskey":
            keys, arms, default = action[1]
            ks = ", ".join(f'"{esc(k)}"' for k in keys)
            out.append(f"\t\t\t\tmatch json_object_has_key(__bytes, &[{ks}]) {{")
            for idx in sorted(arms):
                out.append(f"\t\t\t\t\t{idx} => {{")
                out.append(
                    f"\t\t\t\t\t\tself.{snake(arms[idx])} = Some(serde_json::from_slice::<{fieldty[arms[idx]]}>(__bytes)?);"
                )
                out.append("\t\t\t\t\t\treturn Ok(());")
                out.append("\t\t\t\t\t}")
            if default:
                out.append("\t\t\t\t\t_ => {")
                out.append(
                    f"\t\t\t\t\t\tself.{snake(default)} = Some(serde_json::from_slice::<{fieldty[default]}>(__bytes)?);"
                )
                out.append("\t\t\t\t\t\treturn Ok(());")
                out.append("\t\t\t\t\t}")
            else:
                out.append("\t\t\t\t\t_ => {}")
            out.append("\t\t\t\t}")
            out.append(f'\t\t\t\treturn Err(err_invalid_value("{name}", __data.get()));')
        elif a == "tryarms":
            for field, goty in action[1]:
                out.append(
                    f"\t\t\t\tif let Ok(__v) = serde_json::from_slice::<{vty(goty)}>(__bytes) {{"
                )
                out.append(f"\t\t\t\t\tself.{snake(field)} = Some(__v);")
                out.append("\t\t\t\t\treturn Ok(());")
                out.append("\t\t\t\t}")
            out.append(f'\t\t\t\treturn Err(err_invalid_value("{name}", __data.get()));')
        out.append("\t\t\t}")
    out.append("\t\t\t__k => {")
    out.append(f'\t\t\t\treturn Err(err_invalid_kind("{name}", __k));')
    out.append("\t\t\t}")
    out.append("\t\t}")
    out.append("\t\tOk(())")


def emit_union(u, name, fields, nullable, doc, out):
    """fields: [(go_field_name, rust_inner_type)]"""
    out += doc_rs(doc)
    out.append("#[derive(Clone, Debug, Default, PartialEq)]")
    out.append(f"pub struct {name} {{")
    for fn, ft in fields:
        out.append(f"\tpub {snake(fn)}: Option<{ft}>,")
    out.append("}")
    out.append("")

    # --- Serialize (marshalUnion) ---
    out.append(f"impl Serialize for {name} {{")
    out.append("\tfn serialize<S: Serializer>(&self, __s: S) -> Result<S::Ok, S::Error> {")
    cnt = " + ".join(f"self.{snake(f)}.is_some() as usize" for f, _ in fields) or "0"
    out.append(f"\t\tlet __count = {cnt};")
    if nullable:
        out.append(f'\t\tassert!(__count <= 1, "more than one element of {name} is set");')
        out.append("\t\tif __count == 0 {")
        out.append("\t\t\treturn __s.serialize_unit();")
        out.append("\t\t}")
    else:
        out.append(f'\t\tassert!(__count == 1, "exactly one element of {name} should be set");')
    for fn, _ in fields:
        out.append(f"\t\tif let Some(__v) = &self.{snake(fn)} {{")
        out.append("\t\t\treturn __v.serialize(__s);")
        out.append("\t\t}")
    out.append('\t\tunreachable!("union arm count checked above")')
    out.append("\t}")
    out.append("}")
    out.append("")

    # --- UnmarshalerFrom ---
    fieldty = {f: t for f, t in fields}
    out.append(f"impl json::UnmarshalerFrom for {name} {{")
    out.append(
        "\tfn unmarshal_json_from<R: std::io::Read>(\n"
        "\t\t&mut self,\n"
        "\t\tdec: &mut json::Decoder<R>,\n"
        "\t) -> Result<(), serde_json::Error> {"
    )
    out.append(f"\t\t*self = {name}::default();")
    out.append("\t\tlet __data = dec.read_value()?;")
    out.append("\t\tlet __bytes = __data.get().as_bytes();")
    emit_union_decode(u, name, fieldty, out)
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl<'de> Deserialize<'de> for {name} {{")
    out.append("\tfn deserialize<D: serde::Deserializer<'de>>(__d: D) -> Result<Self, D::Error> {")
    out.append("\t\tjson::deserialize_unmarshaler_from(__d)")
    out.append("\t}")
    out.append("}")
    out.append("")


def emit_struct(st, out, copyable=False):
    out += doc_rs(st.doc)
    derives = "Clone, Debug, Default, PartialEq"
    if copyable:
        derives += ", Copy"
    out.append(f"#[derive({derives}, Serialize)]")
    out.append(f"pub struct {st.name} {{")
    for f in st.fields:
        emit_field_docs(f, out)
        rt, _ = fty(f.goty)
        # Go's *T self-reference (SelectionRange.Parent) needs indirection in
        # Rust or the type has infinite size.
        if rt == f"Option<{st.name}>":
            rt = f"Option<Box<{st.name}>>"
        attrs = []
        if f.skip:
            attrs.append("skip")
        else:
            attrs.append(f'rename = "{esc(f.jname)}"')
            if f.omitzero:
                if _ == "iface":
                    attrs.append('skip_serializing_if = "serde_json::Value::is_null"')
                elif _ is True:
                    attrs.append('skip_serializing_if = "Option::is_none"')
                else:
                    attrs.append('skip_serializing_if = "crate::is_zero"')
        out.append(f'\t#[serde({", ".join(attrs)})]')
        out.append(f"\tpub {snake(f.name)}: {rt},")
        out.append("")
    out.append("}")
    out.append("")

    # --- strict unmarshal (structcodec.go port) ---
    req = [f for f in st.fields if f.required]
    req_idx = {f.name: i for i, f in enumerate(req)}
    out.append(f"impl json::UnmarshalerFrom for {st.name} {{")
    out.append(
        "\tfn unmarshal_json_from<R: std::io::Read>(\n"
        "\t\t&mut self,\n"
        "\t\tdec: &mut json::Decoder<R>,\n"
        "\t) -> Result<(), serde_json::Error> {"
    )
    out.append("\t\tif dec.peek_kind()? != b'{' {")
    out.append("\t\t\treturn Err(err_not_object(dec.peek_kind()?));")
    out.append("\t\t}")
    out.append("\t\tdec.read_token()?;")
    out.append("\t\tlet mut __seen: u64 = 0;")
    out.append("\t\twhile dec.peek_kind()? != b'}' {")
    out.append("\t\t\tlet __name = dec.read_value()?;")
    out.append("\t\t\tlet __key = &__name.get().as_bytes();")
    out.append("\t\t\t// PORT: compare raw token bytes without the quotes, as Go does")
    out.append("\t\t\tmatch &__key[1..__key.len() - 1] {")
    for f in st.fields:
        if f.skip:
            continue
        rt, nilable = fty(f.goty)
        out.append(f'\t\t\t\tb"{esc(f.jname)}" => {{')
        if f.required:
            out.append(f"\t\t\t\t\t__seen |= 1 << {req_idx[f.name]};")
        if nilable is True and not f.nullable:
            out.append("\t\t\t\t\tif dec.peek_kind()? == b'n' {")
            out.append(f'\t\t\t\t\t\treturn Err(err_null("{esc(f.jname)}"));')
            out.append("\t\t\t\t\t}")
        out.append(f"\t\t\t\t\tself.{snake(f.name)} = decode_member(dec)?;")
        out.append("\t\t\t\t}")
    out.append("\t\t\t\t_ => dec.skip_value()?,")
    out.append("\t\t\t}")
    out.append("\t\t}")
    out.append("\t\tdec.read_token()?;")
    if req:
        names = ", ".join(f'"{esc(f.jname)}"' for f in req)
        out.append(f"\t\tconst __REQUIRED: &[&str] = &[{names}];")
        out.append("\t\tif __seen != (1 << __REQUIRED.len()) - 1 {")
        out.append("\t\t\tlet mut __missing = Vec::new();")
        out.append("\t\t\tfor (i, __n) in __REQUIRED.iter().enumerate() {")
        out.append("\t\t\t\tif __seen & (1 << i) == 0 {")
        out.append("\t\t\t\t\t__missing.push(*__n);")
        out.append("\t\t\t\t}")
        out.append("\t\t\t}")
        out.append("\t\t\treturn Err(err_missing(&__missing));")
        out.append("\t\t}")
    out.append("\t\tOk(())")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl<'de> Deserialize<'de> for {st.name} {{")
    out.append("\tfn deserialize<D: serde::Deserializer<'de>>(__d: D) -> Result<Self, D::Error> {")
    out.append("\t\tjson::deserialize_unmarshaler_from(__d)")
    out.append("\t}")
    out.append("}")
    out.append("")


def emit_lenient_struct(st, out, copy_ty=False):
    """Go-default codec: derive serde both ways, null -> zero, absent -> zero."""
    out += doc_rs(st.doc)
    derives = "Clone, Debug, Default, PartialEq"
    if copy_ty:
        derives += ", Copy"
    out.append(f"#[derive({derives}, Serialize, Deserialize)]")
    out.append(f"pub struct {st.name} {{")
    for f in st.fields:
        emit_field_docs(f, out)
        rt, nilable = rty_resolved(f.goty)
        if rt == f"Option<{st.name}>":
            rt = f"Option<Box<{st.name}>>"
        jname = f.jname or f.name
        attrs = [f'rename = "{esc(jname)}"', "default"]
        if rt.startswith("Option<"):
            attrs.append('skip_serializing_if = "Option::is_none"')
        else:
            attrs.append('skip_serializing_if = "crate::is_zero"')
        attrs.append('deserialize_with = "null_to_default"')
        out.append(f'\t#[serde({", ".join(attrs)})]')
        out.append(f"\tpub {snake(f.name)}: {rt},")
        out.append("")
    out.append("}")
    out.append("")


def emit_literal(name, value, doc, out):
    out += doc_rs(doc)
    out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]")
    out.append(f"pub struct {name};")
    out.append("")
    out.append(f"impl Serialize for {name} {{")
    out.append("\tfn serialize<S: Serializer>(&self, __s: S) -> Result<S::Ok, S::Error> {")
    out.append(f'\t\t__s.serialize_str("{esc(value)}")')
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl json::UnmarshalerFrom for {name} {{")
    out.append(
        "\tfn unmarshal_json_from<R: std::io::Read>(\n"
        "\t\t&mut self,\n"
        "\t\tdec: &mut json::Decoder<R>,\n"
        "\t) -> Result<(), serde_json::Error> {"
    )
    out.append("\t\tlet __v = dec.read_value()?;")
    out.append(f'\t\tif __v.get() != "\\"{esc(value)}\\"" {{')
    out.append(f'\t\t\treturn Err(err_literal("{name}", "{esc(value)}", __v.get()));')
    out.append("\t\t}")
    out.append("\t\tOk(())")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl<'de> Deserialize<'de> for {name} {{")
    out.append("\tfn deserialize<D: serde::Deserializer<'de>>(__d: D) -> Result<Self, D::Error> {")
    out.append("\t\tjson::deserialize_unmarshaler_from(__d)")
    out.append("\t}")
    out.append("}")
    out.append("")


def emit_string_enum(name, consts, doc, out):
    out += doc_rs(doc)
    out.append("#[derive(Clone, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]")
    out.append(f"pub struct {name}(pub Cow<'static, str>);")
    out.append("")
    out.append(f"impl {name} {{")
    out.append("\t/// `func (v X) String() string` equivalent")
    out.append("\tpub fn as_str(&self) -> &str {")
    out.append("\t\t&self.0")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl fmt::Display for {name} {{")
    out.append("\tfn fmt(&self, __f: &mut fmt::Formatter<'_>) -> fmt::Result {")
    out.append("\t\t__f.write_str(&self.0)")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl Serialize for {name} {{")
    out.append("\tfn serialize<S: Serializer>(&self, __s: S) -> Result<S::Ok, S::Error> {")
    out.append("\t\t__s.serialize_str(&self.0)")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append(f"impl<'de> Deserialize<'de> for {name} {{")
    out.append("\tfn deserialize<D: serde::Deserializer<'de>>(__d: D) -> Result<Self, D::Error> {")
    out.append("\t\tOk(Self(Cow::Owned(String::deserialize(__d)?)))")
    out.append("\t}")
    out.append("}")
    out.append("")
    if consts:
        out.append(f"impl {name} {{")
        for cname, cval in consts:
            short = cname[len(name):] if cname.startswith(name) else cname
            out.append(f"\t/// `{cname}`")
            out.append(f'\tpub const {short}: {name} = {name}(Cow::Borrowed("{esc(cval)}"));')
        out.append("}")
        out.append("")


def emit_num_enum(name, base, consts, has_string, doc, out):
    rt = GO_PRIMS[base]
    out += doc_rs(doc)
    out.append(
        "#[derive(Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Serialize, Deserialize)]"
    )
    out.append("#[serde(transparent)]")
    out.append(f"pub struct {name}(pub {rt});")
    out.append("")
    out.append(f"impl {name} {{")
    for cname, cval in consts:
        short = cname[len(name):] if cname.startswith(name) else cname
        out.append(f"\t/// `{cname}`")
        out.append(f"\tpub const {short}: {name} = {name}({cval});")
    out.append("}")
    out.append("")
    if has_string:
        out.append(f"impl fmt::Display for {name} {{")
        out.append("\tfn fmt(&self, __f: &mut fmt::Formatter<'_>) -> fmt::Result {")
        out.append("\t\tmatch self.0 {")
        for cname, cval in consts:
            short = cname[len(name):] if cname.startswith(name) else cname
            out.append(f'\t\t\t{cval} => __f.write_str("{short}"),')
        out.append(f'\t\t\t__v => write!(__f, "{name}({{}})", __v),')
        out.append("\t\t}")
        out.append("\t}")
        out.append("}")
        out.append("")
    if name == "ErrorCode":
        out.append("impl std::error::Error for ErrorCode {}")
        out.append("")


def emit_registration(st, funcs, out):
    mb = funcs["Registration"]["MarshalJSONTo"]
    ub = funcs["Registration"]["UnmarshalJSONFrom"]
    marshal_pairs = re.findall(
        r's\.RegisterOptions\.(\w+) != nil:\s*\n\s*method = json\.Value\(`"([^"]+)"`\)',
        mb,
    )
    unmarshal_pairs = re.findall(
        r"case (Method\w+):\s*\n\s*var v (\w+)\s*\n\s*if err := json\.Unmarshal\(rawRegisterOptions, &v\); err != nil \{\s*\n\s*return err\s*\n\s*\}\s*\n\s*s\.RegisterOptions\.(\w+) = &v",
        ub,
    )

    out += doc_rs(st.doc)
    out.append("#[derive(Clone, Debug, Default, PartialEq)]")
    out.append("pub struct Registration {")
    out.append("\t/// `Id string`")
    out.append("\tpub id: String,")
    out.append("")
    out.append('\t/// `RegisterOptions *RegisterOptions` (`json:"-"`) — encoded via')
    out.append("\t/// method dispatch; decoded after `method` is known.")
    out.append("\tpub register_options: Option<RegisterOptions>,")
    out.append("}")
    out.append("")

    out.append("impl Serialize for Registration {")
    out.append("\tfn serialize<S: Serializer>(&self, __s: S) -> Result<S::Ok, S::Error> {")
    out.append('\t\tlet Some(__opts) = &self.register_options else {')
    out.append('\t\t\tpanic!("RegisterOptions must be set");')
    out.append("\t\t};")
    cnt = " + ".join(f"__opts.{snake(f)}.is_some() as usize" for f, _ in marshal_pairs)
    out.append(f"\t\tlet __count = {cnt};")
    out.append('\t\tassert!(__count == 1, "exactly one element of RegisterOptions should be set");')
    out.append("\t\tlet mut __map = __s.serialize_map(Some(3))?;")
    out.append('\t\t__map.serialize_entry("id", &self.id)?;')
    for field, method in marshal_pairs:
        out.append(f"\t\tif let Some(__v) = &__opts.{snake(field)} {{")
        out.append(f'\t\t\t__map.serialize_entry("method", "{esc(method)}")?;')
        out.append('\t\t\t__map.serialize_entry("registerOptions", __v)?;')
        out.append("\t\t}")
    out.append("\t\t__map.end()")
    out.append("\t}")
    out.append("}")
    out.append("")

    out.append("impl json::UnmarshalerFrom for Registration {")
    out.append(
        "\tfn unmarshal_json_from<R: std::io::Read>(\n"
        "\t\t&mut self,\n"
        "\t\tdec: &mut json::Decoder<R>,\n"
        "\t) -> Result<(), serde_json::Error> {"
    )
    out.append("\t\t*self = Registration::default();")
    out.append("\t\tif dec.peek_kind()? != b'{' {")
    out.append("\t\t\treturn Err(err_not_object(dec.peek_kind()?));")
    out.append("\t\t}")
    out.append("\t\tdec.read_token()?;")
    out.append("\t\tlet mut __seen: u64 = 0;")
    out.append("\t\tlet mut __method = String::new();")
    out.append("\t\tlet mut __raw_options: Option<json::Value> = None;")
    out.append("\t\twhile dec.peek_kind()? != b'}' {")
    out.append("\t\t\tlet __name = dec.read_value()?;")
    out.append("\t\t\tlet __key = &__name.get().as_bytes();")
    out.append("\t\t\tmatch &__key[1..__key.len() - 1] {")
    out.append('\t\t\t\tb"id" => {')
    out.append("\t\t\t\t\t__seen |= 1;")
    out.append("\t\t\t\t\tself.id = decode_member(dec)?;")
    out.append("\t\t\t\t}")
    out.append('\t\t\t\tb"method" => {')
    out.append("\t\t\t\t\t__seen |= 2;")
    out.append("\t\t\t\t\t__method = decode_member(dec)?;")
    out.append("\t\t\t\t}")
    out.append('\t\t\t\tb"registerOptions" => {')
    out.append("\t\t\t\t\t__raw_options = Some(dec.read_value()?);")
    out.append("\t\t\t\t}")
    out.append("\t\t\t\t_ => dec.skip_value()?,")
    out.append("\t\t\t}")
    out.append("\t\t}")
    out.append("\t\tdec.read_token()?;")
    out.append("\t\tif __seen != 3 {")
    out.append("\t\t\tlet mut __missing = Vec::new();")
    out.append('\t\t\tif __seen & 1 == 0 { __missing.push("id"); }')
    out.append('\t\t\tif __seen & 2 == 0 { __missing.push("method"); }')
    out.append("\t\t\treturn Err(err_missing(&__missing));")
    out.append("\t\t}")
    out.append("\t\tif let Some(__raw) = __raw_options {")
    out.append("\t\t\tlet mut __opts = RegisterOptions::default();")
    out.append("\t\t\tmatch __method.as_str() {")
    for mconst, ty, field in unmarshal_pairs:
        short = mconst[len("Method"):] if mconst.startswith("Method") else mconst
        out.append(f"\t\t\t\tx if x == Method::{short}.as_str() => {{")
        out.append(
            f"\t\t\t\t\t__opts.{snake(field)} = Some(serde_json::from_slice::<{ty}>(__raw.get().as_bytes())?);"
        )
        out.append("\t\t\t\t}")
    out.append("\t\t\t\t_ => {}")
    out.append("\t\t\t}")
    out.append("\t\t\tself.register_options = Some(__opts);")
    out.append("\t\t}")
    out.append("\t\tOk(())")
    out.append("\t}")
    out.append("}")
    out.append("")
    out.append("impl<'de> Deserialize<'de> for Registration {")
    out.append("\tfn deserialize<D: serde::Deserializer<'de>>(__d: D) -> Result<Self, D::Error> {")
    out.append("\t\tjson::deserialize_unmarshaler_from(__d)")
    out.append("\t}")
    out.append("}")
    out.append("")


