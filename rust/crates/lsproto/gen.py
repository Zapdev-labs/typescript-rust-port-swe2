#!/usr/bin/env python3
"""Translates tsc/internal/lsp/lsproto/lsp_generated.go into src/lsp_generated.rs.

The Go file is generated from the LSP meta model and is extremely regular, so
this translator keys off the exact emission patterns rather than parsing Go
generally:

  * plain structs -> serde Serialize + generated `UnmarshalerFrom` impls that
    reproduce structcodec.go (required-field bits, rejectNull on nilable
    fields, unknown-field skipping)
  * union structs with marshalUnion/unmarshal helpers -> Option-arm structs
    with hand-emitted Serialize/Deserialize dispatch
  * numeric/string named types -> newtypes with const blocks
  * `StringLiteral*` marker types -> exact-match codecs
  * `Resolved*` structs + `resolve()` -> lenient serde + resolve methods
  * `Registration` -> bespoke codec (method-driven registerOptions dispatch)

Usage: gen.py <lsp_generated.go> <lsp_generated.rs>
"""

