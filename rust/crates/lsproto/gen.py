class Field:
    __slots__ = ("name", "goty", "jname", "jopts", "lsp", "doc")

    def __init__(self, name, goty, jname="", jopts=(), lsp="", doc=()):
        self.name, self.goty, self.jname = name, goty, jname
        self.jopts, self.lsp, self.doc = jopts, lsp, doc

    @property
    def required(self):
        return "required" in self.lsp

    @property
    def nullable(self):
        return "nullable" in self.lsp

    @property
    def omitzero(self):
        return "omitzero" in self.jopts

    @property
    def skip(self):
        return self.jname == "-"


class Struct:
    __slots__ = ("name", "fields", "doc")

    def __init__(self, name, doc):
        self.name, self.fields, self.doc = name, [], doc


def parse_top(src):
    decls = []
    pos, n = 0, len(src)
    docbuf = []
    while pos < n:
        if src.startswith("//", pos):
            eol = src.index("\n", pos)
            docbuf.append(src[pos:eol])
            pos = eol + 1
            continue
        line_end = src.index("\n", pos)
        line = src[pos:line_end]
        if not line.strip():
            if not docbuf or pos == 0:
                docbuf = docbuf if pos == 0 else docbuf
            pos = line_end + 1
            continue
        if line.startswith(("package ", "import ", ")", "//")):
            if line.startswith("import ("):
                pos = src.index("\n)", pos) + 3
            else:
                pos = line_end + 1
            continue
        if line.startswith("type ") and " struct {" in line:
            name = re.match(r"type (\w+)", line).group(1)
            end = src.index("\n}\n", pos)
            body = src[line_end + 1 : end]
            st = Struct(name, docbuf)
            docbuf = []
            fdoc = []
            for fl in body.split("\n"):
                fs = fl.strip()
                if fs.startswith("//"):
                    fdoc.append(fs)
                    continue
                if not fs:
                    continue
                fm = re.match(
                    r'(\w+)\s+(.*?)\s*`json:"([^"]*)"(?:\s+lsp:"([^"]*)")?`',
                    fs,
                )
                if fm:
                    fname, gty, jtag, lsp = fm.groups()
                    jp = jtag.split(",")
                    st.fields.append(Field(fname, gty, jp[0], jp[1:], lsp or "", fdoc))
                else:
                    fm2 = re.match(r"(\w+)\s+(\S+)", fs)
                    if fm2:
                        st.fields.append(Field(fm2.group(1), fm2.group(2), doc=fdoc))
                fdoc = []
            decls.append(("struct", st))
            pos = end + 3
            continue
        if line.startswith("type "):
            m = re.match(r"type (\w+) (.*)$", line)
            decls.append(("typealias", (m.group(1), m.group(2).strip().lstrip("= "), docbuf)))
            docbuf = []
            pos = line_end + 1
            continue
        if line.startswith("const ("):
            end = src.index("\n)", pos)
            decls.append(("constblock", (src[line_end + 1 : end], docbuf)))
            docbuf = []
            pos = end + 3
            continue
        if line.startswith("var "):
            if line.startswith("var ("):
                # stringer index tables
                pos = src.index("\n)", pos) + 3
                docbuf = []
                continue
            if line.startswith("var _ "):
                pos = line_end + 1
                docbuf = []
                continue
            decls.append(("var", (line[4:].strip(), docbuf)))
            docbuf = []
            pos = line_end + 1
            continue
        if line.startswith("const ") and not line.startswith("const ("):
            # stringer name table (const _X_name = "...") — stringer data only
            pos = line_end + 1
            docbuf = []
            continue
        if line.startswith("func "):
            end = src.index("\n}\n", pos)
            decls.append(("func", src[pos : end + 3]))
            pos = end + 3
            docbuf = []
            continue
        raise RuntimeError(f"unparsed at {pos}: {line!r}")
    return decls


